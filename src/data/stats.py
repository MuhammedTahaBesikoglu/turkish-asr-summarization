"""Descriptive statistics of the Common Voice splits (clip durations, sentence lengths,
speakers, demographics).

Usage:
    python -m src.data.stats --config configs/data.yaml --out results/data_summary
"""

from __future__ import annotations

import argparse
import json
import statistics
from collections import Counter
from typing import Any

from src.data.common_voice import SPLITS, Clip, load_split, missing_audio

# Whisper's encoder sees at most 30 s of audio per input.
WHISPER_MAX_SECONDS = 30.0


def _quantile(values: list[float], q: float) -> float:
    """Nearest-rank quantile of a non-empty list."""
    ordered = sorted(values)
    index = min(len(ordered) - 1, max(0, round(q * (len(ordered) - 1))))
    return ordered[index]


def _describe(values: list[float]) -> dict[str, float]:
    if not values:
        return {}
    return {
        "mean": statistics.fmean(values),
        "median": statistics.median(values),
        "p95": _quantile(values, 0.95),
        "min": min(values),
        "max": max(values),
    }


def summarize_split(clips: list[Clip]) -> dict[str, Any]:
    """Compute summary statistics for one split."""
    durations = [c.duration_s for c in clips if c.duration_s is not None]
    words = [len(c.sentence.split()) for c in clips]
    clips_per_speaker = Counter(c.client_id for c in clips)
    top_speaker_clips = clips_per_speaker.most_common(1)[0][1] if clips else 0
    return {
        "clips": len(clips),
        "speakers": len(clips_per_speaker),
        "top_speaker_share": top_speaker_clips / len(clips) if clips else 0.0,
        "hours": sum(durations) / 3600,
        "clips_without_duration": len(clips) - len(durations),
        "clips_over_30s": sum(d > WHISPER_MAX_SECONDS for d in durations),
        "duration_s": _describe(durations),
        "words_per_sentence": _describe([float(w) for w in words]),
        "gender": dict(Counter(c.gender or "unspecified" for c in clips).most_common()),
        "age": dict(Counter(c.age or "unspecified" for c in clips).most_common()),
    }


def to_markdown(summary: dict[str, dict[str, Any]], title: str) -> str:
    """Render per-split summaries as Markdown tables."""
    splits = list(summary)
    header = "| Metric | " + " | ".join(splits) + " |"
    sep = "|---" * (len(splits) + 1) + "|"

    def row(label: str, fmt: str, get) -> str:
        return f"| {label} | " + " | ".join(fmt.format(get(summary[s])) for s in splits) + " |"

    lines = [
        f"# {title}",
        "",
        "Generated by `python -m src.data.stats`. Do not edit by hand.",
        "",
        header,
        sep,
        row("Clips", "{:,}", lambda s: s["clips"]),
        row("Speakers", "{:,}", lambda s: s["speakers"]),
        row("Largest speaker share", "{:.1%}", lambda s: s["top_speaker_share"]),
        row("Hours", "{:.2f}", lambda s: s["hours"]),
        row("Duration mean (s)", "{:.2f}", lambda s: s["duration_s"]["mean"]),
        row("Duration median (s)", "{:.2f}", lambda s: s["duration_s"]["median"]),
        row("Duration p95 (s)", "{:.2f}", lambda s: s["duration_s"]["p95"]),
        row("Duration max (s)", "{:.2f}", lambda s: s["duration_s"]["max"]),
        row("Clips > 30 s", "{:,}", lambda s: s["clips_over_30s"]),
        row("Words/sentence mean", "{:.2f}", lambda s: s["words_per_sentence"]["mean"]),
        row("Words/sentence median", "{:.0f}", lambda s: s["words_per_sentence"]["median"]),
        row("Words/sentence max", "{:.0f}", lambda s: s["words_per_sentence"]["max"]),
    ]
    for field in ("gender", "age"):
        keys = sorted({k for s in splits for k in summary[s][field]})
        lines += ["", f"## {field.capitalize()} (clips)", "", header, sep]
        lines += [row(k, "{:,}", lambda s, k=k, f=field: s[f].get(k, 0)) for k in keys]
    return "\n".join(lines) + "\n"


def main() -> None:
    from src.config import load_config, resolve_path

    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", default="configs/data.yaml")
    parser.add_argument("--out", default="results/data_summary", help="Output path without suffix")
    args = parser.parse_args()

    config = load_config(args.config)
    root = resolve_path(config["dataset"]["root"])
    summary: dict[str, dict[str, Any]] = {}
    for split in SPLITS:
        clips = load_split(root, split)
        missing = missing_audio(clips)
        if missing:
            raise FileNotFoundError(
                f"{len(missing)} audio files of {split} missing, e.g. {missing[0]}"
            )
        summary[split] = summarize_split(clips)

    ds = config["dataset"]
    title = (
        f"Common Voice {ds['version']} ({ds['release_date']}) `{ds['locale']}`: split statistics"
    )
    out = resolve_path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.with_suffix(".json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    out.with_suffix(".md").write_text(to_markdown(summary, title), encoding="utf-8")
    print(f"Wrote {out.with_suffix('.md')} and {out.with_suffix('.json')}")


if __name__ == "__main__":
    main()
